import {
  AndroidConfig,
  type ConfigPlugin,
  withInfoPlist,
  withStringsXml,
} from 'expo/config-plugins';
import fs from 'fs';
import path from 'path';

export type AppBlockerPluginProps = {
  /** iOS App Group shared with the Shield extensions. Default: `group.<ios.bundleIdentifier>`. */
  appGroup?: string;
  /**
   * Add the Shield extensions (the iOS block screen). Default `true`. Set `false` if you
   * build your own; they must read the App Group keys documented in the README.
   */
  iosExtensions?: boolean;
  /** Where the editable extension sources are copied, relative to the project root. */
  iosExtensionsDir?: string;
  /** Text shown in Android Accessibility settings. */
  androidAccessibilityServiceDescription?: string;
};

const PACKAGE_ROOT = path.resolve(__dirname, '../..');
const TEMPLATES = path.join(PACKAGE_ROOT, 'ios-extensions');

const withAppBlocker: ConfigPlugin<AppBlockerPluginProps | void> = (config, props) => {
  const {
    iosExtensions = true,
    iosExtensionsDir = 'targets/app-blocker',
    androidAccessibilityServiceDescription,
  } = props || {};
  const bundleId = config.ios?.bundleIdentifier;
  const appGroup = props?.appGroup ?? (bundleId ? `group.${bundleId}` : undefined);

  if (!appGroup) {
    throw new Error(
      'react-native-app-blocker: set ios.bundleIdentifier in your app config, or pass the `appGroup` option.'
    );
  }

  // Set on the config object, not in a mod: prebuild writes ios.entitlements to the
  // entitlements file, and the extension configs read the App Group from here.
  config.ios = config.ios ?? {};
  config.ios.entitlements = config.ios.entitlements ?? {};
  const entitlements = config.ios.entitlements;
  entitlements['com.apple.developer.family-controls'] = true;
  const groups: string[] = entitlements['com.apple.security.application-groups'] ?? [];
  entitlements['com.apple.security.application-groups'] = [...new Set([...groups, appGroup])];

  config = withInfoPlist(config, (c) => {
    c.modResults.AppBlockerAppGroup = appGroup;
    return c;
  });

  if (iosExtensions) {
    const projectRoot: string = (config as any)._internal?.projectRoot ?? process.cwd();
    copyExtensionTemplates(path.resolve(projectRoot, iosExtensionsDir), appGroup);
    const withTargetsDir = require('@bacons/apple-targets/app.plugin');
    config = withTargetsDir(config, { root: `./${iosExtensionsDir}`, match: '*' });
  }

  if (androidAccessibilityServiceDescription) {
    config = withStringsXml(config, (c) => {
      c.modResults = AndroidConfig.Strings.setStringItem(
        [
          {
            $: { name: 'app_blocker_accessibility_service_description', translatable: 'false' },
            _: androidAccessibilityServiceDescription,
          },
        ],
        c.modResults
      );
      return c;
    });
  }

  return config;
};

/**
 * Copies each extension folder once, so user edits survive. AppBlockerConfig.swift is
 * rewritten every time so the App Group always matches the config.
 */
function copyExtensionTemplates(destRoot: string, appGroup: string) {
  for (const name of fs.readdirSync(TEMPLATES)) {
    const dest = path.join(destRoot, name);
    if (!fs.existsSync(dest)) {
      fs.cpSync(path.join(TEMPLATES, name), dest, { recursive: true });
    }
    fs.writeFileSync(
      path.join(dest, 'AppBlockerConfig.swift'),
      `// Generated by react-native-app-blocker on every prebuild. Do not edit.\n` +
        `let appBlockerAppGroup = ${JSON.stringify(appGroup)}\n`
    );
  }
}

export default withAppBlocker;
